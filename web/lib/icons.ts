/** Inner SVG markup for an icon name (or an Expo icon name, through ALIAS). Unknown names draw "other". */
export function iconMarkup(name: string): string {
  const g = G[resolve(name)] ?? G.other
  return (g.b ? `<g fill="currentColor" fill-opacity=".2" stroke="none">${g.b}</g>` : '') + line((g.b ?? '') + (g.d ?? '') + (g.o ?? ''))
}

